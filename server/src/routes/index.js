import { Router } from 'express';
import auth from './authRoutes.js';
import leads from './leadRoutes.js';
import properties from './propertyRoutes.js';
import content from './contentRoutes.js';
import assistant from './assistantRoutes.js';
import { requireAuth } from '../middleware/auth.js';
import { dashboard } from '../controllers/leadController.js';
import { asyncHandler,ok } from '../utils/api.js';
import { databaseReady } from '../config/db.js';
import { isProduction } from '../config/env.js';
const router=Router();
router.get('/health/live',(_req,res)=>ok(res,{status:'ok',timestamp:new Date().toISOString()}));
router.get('/health',(_req,res)=>{const ready=databaseReady()||!isProduction;return res.status(ready?200:503).json({success:ready,data:{status:ready?'ok':'unavailable',database:databaseReady()?'connected':'degraded',timestamp:new Date().toISOString()}})});
router.use('/auth',auth);router.use('/leads',leads);router.use('/properties',properties);router.use('/content',content);router.use('/assistant',assistant);router.get('/admin/dashboard',requireAuth,asyncHandler(dashboard));export default router;
